import { writeFileSync } from "node:fs";
import {
  chmod,
  lstat,
  mkdir,
  readdir,
  readFile,
  readlink,
  rm,
  symlink,
  utimes,
  writeFile,
} from "node:fs/promises";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { run } from "../src/cli.ts";
import { configJson } from "../src/instance/files.ts";
import { makeCert } from "./certs.ts";
import { fakeHost, type FakeHost } from "./fakehost.ts";
import { fakeNet, type FakeNet } from "./fakenet.ts";
import { harness, type Harness, type HarnessOptions } from "./helpers.ts";

let h: Harness;
let host: FakeHost;
let net: FakeNet;
/** While true, the faked `df` fails, so free space cannot be read. */
let dfFails = false;
afterEach(() => h.cleanup());

const HOSTNAME = "family.example.org";
const UNIT = "dcabsm@family";
const dir = (...parts: string[]) => join(h.ctx.paths.instances, "family", ...parts);
const text = () => h.out.join("\n");
const doctor = (...args: string[]) => run(["host", "doctor", ...args], h.ctx);
const read = (path: string) => readFile(path, "utf8");

/** A Host that setup has finished with and that runs one healthy Instance, `family`, on Release 26.11.1. */
async function familyHost(opts: HarnessOptions = {}): Promise<void> {
  host = fakeHost();
  net = fakeNet();
  dfFails = false;
  h = await harness({
    setUp: false,
    net,
    ...opts,
    runner(command, args) {
      if (command === "openssl") {
        const made = makeCert(args[args.indexOf("-subj") + 1]!.slice("/CN=".length));
        writeFileSync(args[args.indexOf("-keyout") + 1]!, made.key);
        writeFileSync(args[args.indexOf("-out") + 1]!, made.cert);
        return { code: 0, stdout: "", stderr: "" };
      }
      if (command === "df" && dfFails) return { code: 1, stdout: "", stderr: "df: failed" };
      return host.run(command, args);
    },
  });
  expect(await run(["host", "setup", "--yes"], h.ctx)).toBe(0);
  const create = ["instance", "create", "family", "--hostname", HOSTNAME, "--self-signed"];
  expect(await run(create, h.ctx)).toBe(0);
  expect(await run(["backup", "schedule", "family", "off"], h.ctx)).toBe(0);
  net.served[HOSTNAME] = await read(dir("nginx", "cert.pem"));
  net.dns[HOSTNAME] = ["127.0.0.1"];
  // The account the tests run as stands in for dcabsm-family, so ownership matches.
  await accountIs(process.getuid!(), process.getgid!());
  h.out.length = 0;
  h.calls.length = 0;
}

async function accountIs(uid: number, gid: number): Promise<void> {
  await mkdir(h.ctx.paths.under("/etc"), { recursive: true });
  await writeFile(
    h.ctx.paths.under("/etc/passwd"),
    `root:x:0:0::/root:/bin/bash\ndcabsm-family:x:${uid}:${gid}::/nonexistent:/usr/sbin/nologin\n`,
  );
}

const calls = (command: string) => h.calls.filter((c) => c.command === command);
const sysctl = (verb: string) =>
  h.calls
    .filter((c) => c.command === "systemctl" && c.args[0] === verb)
    .map((c) => c.args.join(" "));

describe("a healthy Instance", () => {
  it("passes every Instance check and exits 0", async () => {
    await familyHost();
    expect(await doctor()).toBe(0);
    expect(text()).not.toMatch(/[✗!]/);
    expect(text()).toContain("✓ Every Instance's config.json matches its record");
    expect(text()).toContain("✓ Every Instance's vhost.conf matches");
    expect(text()).toContain("✓ Every Instance's port is its own");
  });

  it("runs the certificate test for it", async () => {
    await familyHost();
    delete net.served[HOSTNAME];
    expect(await doctor()).not.toBe(0);
    expect(text()).toContain(`✗ family: Could not connect to 127.0.0.1:443 as ${HOSTNAME}`);
  });
});

describe("config.json", () => {
  it("is left alone when it matches", async () => {
    await familyHost();
    const before = await read(dir("config", "config.json"));
    expect(await doctor("--fix", "--yes")).toBe(0);
    expect(await read(dir("config", "config.json"))).toBe(before);
  });

  it("is regenerated by --fix, and --yes restarts a running Instance", async () => {
    await familyHost();
    const good = await read(dir("config", "config.json"));
    await writeFile(dir("config", "config.json"), '{"port": 1}\n');
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: config.json differs from its record  (host doctor --fix)");
    expect(await read(dir("config", "config.json"))).toBe('{"port": 1}\n');

    h.out.length = 0;
    expect(await doctor("--fix", "--yes")).toBe(0);
    expect(await read(dir("config", "config.json"))).toBe(good);
    expect(sysctl("restart")).toEqual([`restart ${UNIT}`]);
    expect(calls("chown").map((c) => c.args.join(" "))).toContain(
      `root:dcabsm-family ${dir("config", "config.json")}`,
    );
  });

  it("asks separately to restart; declined, it reports restart needed", async () => {
    await familyHost({ interactive: true, answers: ["f", "n"] });
    host.started[UNIT] = "Thu 2026-01-01 00:00:00 UTC";
    await writeFile(dir("config", "config.json"), "{}\n");
    expect(await doctor("--fix")).toBe(1);
    expect(h.asked).toEqual([
      "fix / skip / all? [f/s/a] ",
      "Restart family now to load the new config.json? [y/N] ",
    ]);
    expect(sysctl("restart")).toEqual([]);
    expect(await read(dir("config", "config.json"))).toContain('"port": 15127');
    expect(text()).toContain("! family: restart needed, config.json changed after it started");
  });

  it("is not restarted when the Instance is stopped", async () => {
    await familyHost();
    host.active.delete(UNIT);
    await writeFile(dir("config", "config.json"), "{}\n");
    expect(await doctor("--fix", "--yes")).toBe(0);
    expect(sysctl("restart")).toEqual([]);
  });

  it("reports a setting in the record that config.json does not carry", async () => {
    await familyHost();
    const record = JSON.parse(await read(dir("config", "instance.json")));
    record.settings = { "upload-limit-mb": 30 };
    await writeFile(dir("config", "instance.json"), JSON.stringify(record));
    expect(await doctor()).toBe(1);
    expect(text()).toContain("family: config.json differs from its record");
  });
});

describe("vhost.conf", () => {
  it("is regenerated by --fix with nginx -t and a reload, keeping the old copy", async () => {
    await familyHost();
    const good = await read(dir("nginx", "vhost.conf"));
    await writeFile(dir("nginx", "vhost.conf"), "# edited\n");
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: vhost.conf differs from what DCABSM generates");

    expect(await doctor("--fix", "--yes")).toBe(0);
    expect(await read(dir("nginx", "vhost.conf"))).toBe(good);
    expect(calls("nginx").some((c) => c.args[0] === "-t")).toBe(true);
    expect(sysctl("reload")).toContain("reload nginx");
    const replaced = h.ctx.paths.under("/etc/dcabsm/replaced");
    const stamps = await readdir(replaced);
    expect(
      await read(join(replaced, stamps[0]!, "/srv/dcabsm/instances/family/nginx/vhost.conf")),
    ).toBe("# edited\n");
  });

  it("puts the old file back and does not reload when nginx -t fails", async () => {
    await familyHost();
    await writeFile(dir("nginx", "vhost.conf"), "# edited\n");
    host.nginxTest = { code: 1, stdout: "", stderr: "nginx: [emerg] bad" };
    await doctor("--fix", "--yes");
    expect(await read(dir("nginx", "vhost.conf"))).toBe("# edited\n");
    expect(sysctl("reload")).toEqual([]);
    expect(text()).toContain("Could not fix: family: vhost.conf differs");
  });

  it("is written again when missing", async () => {
    await familyHost();
    const good = await read(dir("nginx", "vhost.conf"));
    await rm(dir("nginx", "vhost.conf"));
    expect(await doctor("--fix", "--yes")).toBe(0);
    expect(await read(dir("nginx", "vhost.conf"))).toBe(good);
  });
});

describe("an Instance with an unfinished Release change", () => {
  it("is not judged on generated files that rollback will rewrite", async () => {
    await familyHost();
    await writeFile(dir("config", "config.json"), "{}\n");
    await writeFile(dir("nginx", "vhost.conf"), "# edited\n");
    await writeFile(
      dir(".changing-release"),
      JSON.stringify({ operation: "upgrade", from: "26.10.0", to: "26.11.1", backup: "/x" }),
    );
    expect(await doctor()).toBe(2);
    expect(text()).toContain(
      "✗ family has an unfinished Release change (upgrade, 26.10.0 → 26.11.1)",
    );
    expect(text()).not.toContain("config.json differs");
    expect(text()).not.toContain("vhost.conf differs");
  });
});

describe("Instance settings", () => {
  it("notes a setting the current Release does not use", async () => {
    await familyHost();
    expect(await run(["release", "install", "26.10.0"], h.ctx)).toBe(0);
    const record = JSON.parse(await read(dir("config", "instance.json")));
    record.settings = { "simplefin-allowed-networks": "10.0.0.0/8" };
    await writeFile(dir("config", "instance.json"), JSON.stringify(record));
    // 26.11.0 added the setting; an Instance on 26.10.0 keeps it in the record but cannot use it.
    await rm(dir("release"));
    await symlink(join(h.ctx.paths.releases, "26.10.0"), dir("release"));
    net.serverVersion = "26.10.0";
    await writeFile(dir("config", "config.json"), configJson("family", record, "26.10.0"));
    expect(await doctor()).toBe(0);
    expect(text()).toContain(
      "· family: simplefin-allowed-networks is set but not used by Release 26.10.0",
    );
  });
});

describe("the account and ownership", () => {
  it("fixes a wrong mode and owner with chown and chmod", async () => {
    await familyHost();
    await chmod(dir("data"), 0o755);
    await accountIs(process.getuid!() + 1000, process.getgid!() + 1000);
    expect(await doctor()).toBe(1);
    expect(text()).toContain("family: /srv/dcabsm/instances/family/data is owned by");
    expect(text()).toContain("not dcabsm-family:dcabsm-family and has mode 755, not 700");

    h.calls.length = 0;
    await doctor("--fix", "--yes");
    expect((await lstat(dir("data"))).mode & 0o777).toBe(0o700);
    expect(calls("chown").map((c) => c.args.join(" "))).toContain(
      `dcabsm-family:dcabsm-family ${dir("data")}`,
    );
  });

  it("fixes a config.json that Nginx or the Instance account could not read", async () => {
    await familyHost();
    await chmod(dir("config", "config.json"), 0o666);
    expect(await doctor()).toBe(1);
    expect(text()).toContain("config/config.json has mode 666, not 640");
    await doctor("--fix", "--yes");
    expect((await lstat(dir("config", "config.json"))).mode & 0o777).toBe(0o640);
  });

  it("recreates a missing account with useradd, then repairs ownership", async () => {
    await familyHost();
    await writeFile(h.ctx.paths.under("/etc/passwd"), "root:x:0:0::/root:/bin/bash\n");
    expect(await doctor()).toBe(2);
    expect(text()).toContain("✗ family: the account dcabsm-family is missing  (host doctor --fix)");

    h.calls.length = 0;
    await doctor("--fix", "--yes");
    const useradd = calls("useradd");
    expect(useradd).toHaveLength(1);
    expect(useradd[0]!.args.at(-1)).toBe("dcabsm-family");
    expect(calls("chown").map((c) => c.args.join(" "))).toContain(
      `dcabsm-family:dcabsm-family ${dir("data")}`,
    );
  });

  it("reports a missing certificate or key and points to cert update, with no fix", async () => {
    await familyHost();
    await rm(dir("nginx", "cert.pem"));
    await rm(dir("nginx", "key.pem"));
    // The certificate test fails too (exit 2); this check adds the warnings and the pointer.
    expect(await doctor("--fix", "--yes")).toBe(2);
    expect(text()).toContain("! family: /srv/dcabsm/instances/family/nginx/cert.pem is missing");
    expect(text()).toContain("! family: /srv/dcabsm/instances/family/nginx/key.pem is missing");
    expect(text()).toContain("sudo dcabsm cert update family");
    await expect(lstat(dir("nginx", "cert.pem"))).rejects.toThrow();
  });

  it("recreates a missing directory", async () => {
    await familyHost();
    await rm(dir("user-files"), { recursive: true });
    expect(await doctor()).toBe(1);
    expect(text()).toContain("family: /srv/dcabsm/instances/family/user-files is missing");
    await doctor("--fix", "--yes");
    expect((await lstat(dir("user-files"))).mode & 0o777).toBe(0o700);
  });
});

describe("ports and /info", () => {
  const listener = (port: number, who: string, pid: number) =>
    `LISTEN 0 511 127.0.0.1:${port} 0.0.0.0:* users:(("${who}",pid=${pid},fd=7))\n`;

  it("accepts the Instance's own process on its port", async () => {
    await familyHost();
    host.mainPid[UNIT] = 321;
    host.listeners = listener(15127, "node", 321);
    expect(await doctor()).toBe(0);
  });

  it("reports a port used by something else", async () => {
    await familyHost();
    host.mainPid[UNIT] = 321;
    host.listeners = listener(15127, "python3", 999);
    expect(await doctor()).toBe(2);
    expect(text()).toContain("✗ family: port 15127 is in use by python3 (pid 999)");
  });

  it("reports a port listened on while the Instance is stopped", async () => {
    await familyHost();
    host.active.delete(UNIT);
    host.listeners = listener(15127, "python3", 999);
    expect(await doctor()).toBe(2);
    expect(text()).toContain("family: port 15127 is in use by python3 (pid 999)");
  });

  it("reports a port that is in another Instance's record", async () => {
    await familyHost();
    const other = join(h.ctx.paths.instances, "second", "config");
    await mkdir(other, { recursive: true });
    await writeFile(
      join(other, "instance.json"),
      JSON.stringify({ port: 15127, hostname: "second.example.org", scheduledBackups: false }),
    );
    expect(await doctor()).toBe(2);
    expect(text()).toContain("✗ family: port 15127 is also in the record of second");
    expect(text()).toContain("✗ second: port 15127 is also in the record of family");
  });

  it("reports a running version that is not the Instance's Release", async () => {
    await familyHost();
    net.serverVersion = "26.10.0";
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: /info reports 26.10.0, but its Release is 26.11.1");
  });

  it("reports an active unit whose /info does not answer", async () => {
    await familyHost();
    net.serverUp = false;
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: its unit is active but /info did not answer on port 15127");
  });

  it("does not ask /info of a stopped Instance", async () => {
    await familyHost();
    host.active.delete(UNIT);
    net.fetched.length = 0;
    expect(await doctor()).toBe(0);
    expect(net.fetched.some((u) => u.endsWith("/info"))).toBe(false);
  });
});

describe("Backups", () => {
  const backupDir = () => h.ctx.paths.under("/srv/dcabsm/backups/family");
  const archive = async (stamp: string, kind = "scheduled", bytes = 10) => {
    await mkdir(backupDir(), { recursive: true, mode: 0o700 });
    await chmod(backupDir(), 0o700);
    await writeFile(join(backupDir(), `${stamp}-${kind}-26.11.1.tar.gz`), "x".repeat(bytes), {
      mode: 0o600,
    });
  };
  // The record says when the Instance was created; rewrite it to put that in the past.
  const createdAt = async (iso: string | undefined) => {
    const path = dir("config", "instance.json");
    const rec = JSON.parse(await read(path));
    if (iso === undefined) delete rec.createdAt;
    else rec.createdAt = iso;
    await writeFile(path, JSON.stringify(rec));
  };
  const scheduledOn = async () => {
    expect(await run(["backup", "schedule", "family", "on"], h.ctx)).toBe(0);
  };

  it("warns when scheduled Backups are on and none is newer than 48 hours", async () => {
    await familyHost();
    await scheduledOn();
    await createdAt("2026-11-01T00:00:00Z");
    await archive("20261105T033000Z");
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: no scheduled Backup in the last 48 hours");
  });

  it("warns when there is no scheduled Backup at all", async () => {
    await familyHost();
    await scheduledOn();
    await createdAt("2026-11-01T00:00:00Z");
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: no scheduled Backup in the last 48 hours");
  });

  it("does not warn for an Instance younger than 48 hours that has no scheduled Backup yet", async () => {
    await familyHost();
    await scheduledOn();
    expect(await doctor()).toBe(0);
    expect(text()).not.toContain("no scheduled Backup");
  });

  it("warns once the Instance is older than 48 hours", async () => {
    await familyHost();
    await scheduledOn();
    await createdAt("2026-11-07T11:00:00Z"); // 49 hours before the faked clock
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: no scheduled Backup in the last 48 hours");
  });

  for (const [what, value] of [
    ["in the future", "2099-01-01T00:00:00Z"],
    ["not a date", "yesterday-ish"],
  ] as const) {
    it(`counts a creation time that is ${what} as not young, so it still warns`, async () => {
      await familyHost();
      await scheduledOn();
      await createdAt(value);
      expect(await doctor()).toBe(1);
      expect(text()).toContain("! family: no scheduled Backup in the last 48 hours");
    });
  }

  it("keeps warning for an older Instance whose record has no creation time", async () => {
    await familyHost();
    await scheduledOn();
    await createdAt(undefined);
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: no scheduled Backup in the last 48 hours");
  });

  it("passes with a scheduled Backup from last night", async () => {
    await familyHost();
    await scheduledOn();
    await archive("20261109T033000Z");
    expect(await doctor()).toBe(0);
  });

  it("does not warn when scheduled Backups are off", async () => {
    await familyHost();
    expect(await doctor()).toBe(0);
    expect(text()).not.toContain("no scheduled Backup");
  });

  it("warns when the backup filesystem lacks room for the next Nightly run", async () => {
    await familyHost();
    await scheduledOn();
    // The fake `df` reports 99 KiB free.
    await archive("20261109T033000Z", "scheduled", 100 * 1024);
    expect(await doctor()).toBe(1);
    expect(text()).toContain("the next Nightly run would not fit");
  });

  it("warns that it could not measure when free space cannot be read", async () => {
    await familyHost();
    await scheduledOn();
    await archive("20261109T033000Z");
    dfFails = true;
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! Couldn't measure the free space on the backup filesystem");
  });

  it("counts only Instances with scheduled Backups on", async () => {
    await familyHost();
    await archive("20261109T033000Z", "manual", 100 * 1024);
    expect(await doctor()).toBe(0);
  });
});

describe("a Release's node link", () => {
  const releaseDir = () => join(h.ctx.paths.releases, "26.11.1");

  it("passes when it points to node/<major>", async () => {
    await familyHost();
    expect(await doctor()).toBe(0);
    expect(text()).toContain("✓ Every Release's node link matches its Node major");
  });

  it("reports a link that does not match .dcabsm-node-major, and --fix repoints it", async () => {
    await familyHost();
    const major = (await read(join(releaseDir(), ".dcabsm-node-major"))).trim();
    const wanted = join(h.ctx.paths.node, major);
    await chmod(releaseDir(), 0o755);
    await rm(join(releaseDir(), "node"));
    await symlink(join(h.ctx.paths.node, "99"), join(releaseDir(), "node"));
    await chmod(releaseDir(), 0o555);
    expect(await doctor()).toBe(2);
    expect(text()).toContain(
      `Release 26.11.1's node link points to ${join(h.ctx.paths.node, "99")}, not node/${major}`,
    );

    await doctor("--fix", "--yes");
    expect(await readlink(join(releaseDir(), "node"))).toBe(wanted);
    expect((await lstat(releaseDir())).mode & 0o777).toBe(0o555);
  });

  it("reports a missing link", async () => {
    await familyHost();
    await chmod(releaseDir(), 0o755);
    await rm(join(releaseDir(), "node"));
    await chmod(releaseDir(), 0o555);
    expect(await doctor()).toBe(2);
    expect(text()).toMatch(/Release 26\.11\.1 has no node link; it should point to node\/\d+/);
    await doctor("--fix", "--yes");
    expect((await lstat(join(releaseDir(), "node"))).isSymbolicLink()).toBe(true);
  });
});

describe("a restart that is needed after config.json changed", () => {
  it("is reported when config.json is newer than the unit's start, and not once restarted", async () => {
    await familyHost();
    host.started[UNIT] = "Thu 2026-01-01 00:00:00 UTC";
    const now = new Date();
    await utimes(dir("config", "config.json"), now, now);
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: restart needed, config.json changed after it started");
    expect(await run(["instance", "restart", "family"], h.ctx)).toBe(0);
    h.out.length = 0;
    expect(await doctor()).toBe(0);
  });
});

describe("a unit that started in the same second config.json was written", () => {
  it("is not reported: systemd's start time has whole seconds, a file's mtime has milliseconds", async () => {
    await familyHost();
    host.started[UNIT] = "Thu 2026-01-01 00:00:00 UTC";
    const written = new Date("2026-01-01T00:00:00.700Z");
    await utimes(dir("config", "config.json"), written, written);
    expect(await doctor()).toBe(0);
    expect(text()).not.toContain("restart needed");
  });
});

describe("a unit start time that cannot be read", () => {
  it("warns that it could not measure, instead of staying silent", async () => {
    await familyHost();
    host.started[UNIT] = "";
    expect(await doctor()).toBe(1);
    expect(text()).toContain("! family: couldn't measure when its unit started");
  });
});
