import { join } from "node:path";
import type { Context } from "../context.ts";
import { CliError, firstLine } from "../errors.ts";
import { writeFileAtomic } from "../fsutil.ts";
import { listen443 } from "../host/owned.ts";
import { accountOf, instanceDir, logicalDir, type InstanceRecord } from "./record.ts";
import { bodyLimitMb, SETTINGS, usedBy } from "./setting-table.ts";

const HEADER = "# Generated by DCABSM, never edited by hand. `dcabsm host doctor` flags changes.\n";

/** `config.json`, generated from the record (spec 4.4). Never writes `openId.*`. */
export function configJson(name: string, record: InstanceRecord, release: string): string {
  const dir = logicalDir(name);
  const config: Record<string, unknown> = {
    dataDir: `${dir}/data`,
    serverFiles: `${dir}/server-files`,
    userFiles: `${dir}/user-files`,
    hostname: "127.0.0.1",
    port: record.port,
    trustedProxies: ["127.0.0.1/32"],
    allowedLoginMethods: ["password", "openid"],
    trustedAuthProxies: [] as string[],
  };
  // Only settings the Release knows: Actual refuses to start on a key it doesn't (spec 4.4).
  for (const def of SETTINGS) {
    const value = record.settings?.[def.key];
    if (value === undefined || !usedBy(def, release)) continue;
    const parts = def.actualKey.split(".");
    let target = config;
    for (const part of parts.slice(0, -1)) {
      target = (target[part] ??= {}) as Record<string, unknown>;
    }
    target[parts.at(-1)!] = def.toConfig(value);
  }
  return `${JSON.stringify(config, null, 2)}\n`;
}

/** Writes `config.json` for the Release, root-owned and readable by the Instance account. */
export async function writeConfigJson(
  ctx: Context,
  name: string,
  record: InstanceRecord,
  release: string,
): Promise<void> {
  const path = join(instanceDir(ctx, name), "config", "config.json");
  await writeFileAtomic(path, configJson(name, record, release), 0o640);
  const res = await ctx.runner.run("chown", [`root:${accountOf(name)}`, path]);
  if (res.code !== 0) {
    throw new CliError(`chown failed: ${firstLine(res.stderr, `exit ${res.code}`)}`);
  }
}

/** The vhost (spec 5.2): the same template for every Instance. */
export function vhostConf(name: string, record: InstanceRecord, ipv6: boolean): string {
  const dir = logicalDir(name);
  const listen80 = `    listen 80;\n${ipv6 ? "    listen [::]:80;\n" : ""}`;
  // The +1 leaves Nginx slightly above the largest of Actual's own upload limits.
  return `${HEADER}server {
${listen443(ipv6, "ssl")}    server_name ${record.hostname};
    ssl_certificate ${dir}/nginx/cert.pem;
    ssl_certificate_key ${dir}/nginx/key.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size ${bodyLimitMb(record.settings)}m;

    location / {
        proxy_pass http://127.0.0.1:${record.port};
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Actual-Password "";
    }
}

server {
${listen80}    server_name ${record.hostname};

    location /.well-known/acme-challenge/ {
        root /srv/dcabsm/acme;
    }

    location / {
        return 301 https://$host$request_uri;
    }
}
`;
}
