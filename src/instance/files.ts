import { listen443 } from "../host/owned.ts";
import { logicalDir, type InstanceRecord } from "./record.ts";

const HEADER = "# Generated by DCABSM, never edited by hand. `dcabsm host doctor` flags changes.\n";

/** The largest of Actual's upload limits, in MB, at its defaults (spec 5.2). */
export const DEFAULT_UPLOAD_LIMIT_MB = 50;

/** `config.json`, generated from the record (spec 4.4). Never writes `openId.*`. */
export function configJson(name: string, record: InstanceRecord): string {
  const dir = logicalDir(name);
  const config = {
    dataDir: `${dir}/data`,
    serverFiles: `${dir}/server-files`,
    userFiles: `${dir}/user-files`,
    hostname: "127.0.0.1",
    port: record.port,
    trustedProxies: ["127.0.0.1/32"],
    allowedLoginMethods: ["password", "openid"],
    trustedAuthProxies: [] as string[],
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

/** The vhost (spec 5.2): the same template for every Instance. */
export function vhostConf(name: string, record: InstanceRecord, ipv6: boolean): string {
  const dir = logicalDir(name);
  const listen80 = `    listen 80;\n${ipv6 ? "    listen [::]:80;\n" : ""}`;
  return `${HEADER}server {
${listen443(ipv6, "ssl")}    server_name ${record.hostname};
    ssl_certificate ${dir}/nginx/cert.pem;
    ssl_certificate_key ${dir}/nginx/key.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size ${DEFAULT_UPLOAD_LIMIT_MB + 1}m;

    location / {
        proxy_pass http://127.0.0.1:${record.port};
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Actual-Password "";
    }
}

server {
${listen80}    server_name ${record.hostname};

    location /.well-known/acme-challenge/ {
        root /srv/dcabsm/acme;
    }

    location / {
        return 301 https://$host$request_uri;
    }
}
`;
}
